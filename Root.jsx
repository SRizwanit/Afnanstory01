// Root.jsx (v2 FINAL, Step 35; Thumbnail wired in Step 36b) — registers every composition and still Remotion can render.
// Exports : RemotionRoot (NAMED, required by index.js) + default; DEFAULT_PROPS; THUMB_DEFAULTS; PROPS_SCHEMA;
//           pure helpers (testable): toBool, normalizeProps(p), resolveMetadata({props}), resolveThumbMetadata({props}), THUMB_SIZES
// Compositions (ids NEVER change):
//   Vertical   1080x1920  @ FPS  Story   (4K = --scale=2 -> 2160x3840)
//   Horizontal 1920x1080  @ FPS  Story   (4K = --scale=2 -> 3840x2160)
//   Stills     ThumbnailV 1080x1920 · ThumbnailH 1920x1080   (render:  npx remotion still index.js ThumbnailH out.png [--scale=2])
// Props   : Story  = { part='horror1', debug=false, intro=true, outro=true }   (override with --props='{"intro":false}')
//           Thumb  = { part='horror1', title='লাহুরিয়ার রহস্য' (TODO(user): real title), subtitle='' }
//           Booleans may arrive as the strings "true"/"false"/"0"/"no"/"off" from the CLI; unknown keys are dropped.
// Needs   : Story.jsx (Story, totalFramesFor) · story_data.json · theme.js (FPS, COLORS, FONT_TITLE, FONT_LABEL, LAYERS, useLayout)
// Used by : index.js (registerRoot).
// Notes   : durationInFrames comes from story_data.json through calculateMetadata, so `--props` can switch intro/outro without
//           editing code. story_data.json is regenerated by the Action (`build_data.py --part <part> --intro 60 --outro 90`); here we
//           only guard that it matches `part`. Geometry only from useLayout(); deterministic (no Math.random / CSS animation).
// NOTE    : the two stills render Thumbnail.jsx (Step 36); the temporary ThumbnailStub of Step 35 was removed in Step 36b.
import React from 'react';
import {Composition, Still} from 'remotion';
import data from './story_data.json';
import {Story, totalFramesFor} from './Story.jsx';
import Thumbnail from './Thumbnail.jsx';
import {FPS} from './theme.js';

export const DEFAULT_PROPS = {part: 'horror1', debug: false, intro: true, outro: true};
export const THUMB_DEFAULTS = {part: 'horror1', title: 'লাহুরিয়ার রহস্য', subtitle: ''}; // TODO(user): real title
export const THUMB_SIZES = {ThumbnailV: {width: 1080, height: 1920}, ThumbnailH: {width: 1920, height: 1080}};

// Documentation of the final props (plain object: no zod dependency needed).
export const PROPS_SCHEMA = {
  story: {part: 'string', debug: 'boolean', intro: 'boolean', outro: 'boolean'},
  thumbnail: {part: 'string', title: 'string', subtitle: 'string'},
};

// CLI/Studio props may arrive as booleans or as the strings "true"/"false".
export const toBool = (v, fallback) => {
  if (v === undefined || v === null) return fallback;
  if (typeof v === 'string') return !['false', '0', 'no', 'off', ''].includes(v.trim().toLowerCase());
  return Boolean(v);
};

const toStr = (v, fallback) => (typeof v === 'string' && v.trim() !== '' ? v : fallback);

// Pure (testable): the part must match the generated story_data.json.
const guardPart = (part) => {
  if (part !== data.part) {
    throw new Error(
      `story_data.json is for part "${data.part}" but part "${part}" was requested. ` +
        `Run: python3 build_data.py --part ${part}`
    );
  }
};

// Pure: normalise Story props (drops unknown keys, converts strings).
export const normalizeProps = (p) => {
  const q = p || {};
  const part = toStr(q.part, DEFAULT_PROPS.part);
  return {
    part,
    debug: toBool(q.debug, DEFAULT_PROPS.debug),
    intro: toBool(q.intro, DEFAULT_PROPS.intro),
    outro: toBool(q.outro, DEFAULT_PROPS.outro),
  };
};

// Used as calculateMetadata for Vertical and Horizontal.
export const resolveMetadata = ({props}) => {
  const n = normalizeProps(props);
  guardPart(n.part);
  return {durationInFrames: totalFramesFor(data, n.intro, n.outro), props: n};
};

// Used as calculateMetadata for the two thumbnail stills (props only; a Still has no duration).
export const resolveThumbMetadata = ({props}) => {
  const q = props || {};
  const part = toStr(q.part, THUMB_DEFAULTS.part);
  guardPart(part);
  return {props: {part, title: toStr(q.title, THUMB_DEFAULTS.title), subtitle: typeof q.subtitle === 'string' ? q.subtitle : ''}};
};

export const RemotionRoot = () => {
  const dur = totalFramesFor(data, true, true);
  return (
    <>
      <Composition
        id="Vertical"
        component={Story}
        width={1080}
        height={1920}
        fps={FPS}
        durationInFrames={dur}
        defaultProps={DEFAULT_PROPS}
        calculateMetadata={resolveMetadata}
      />
      <Composition
        id="Horizontal"
        component={Story}
        width={1920}
        height={1080}
        fps={FPS}
        durationInFrames={dur}
        defaultProps={DEFAULT_PROPS}
        calculateMetadata={resolveMetadata}
      />
      <Still
        id="ThumbnailV"
        component={Thumbnail}
        width={THUMB_SIZES.ThumbnailV.width}
        height={THUMB_SIZES.ThumbnailV.height}
        defaultProps={THUMB_DEFAULTS}
        calculateMetadata={resolveThumbMetadata}
      />
      <Still
        id="ThumbnailH"
        component={Thumbnail}
        width={THUMB_SIZES.ThumbnailH.width}
        height={THUMB_SIZES.ThumbnailH.height}
        defaultProps={THUMB_DEFAULTS}
        calculateMetadata={resolveThumbMetadata}
      />
    </>
  );
};

export default RemotionRoot;
